// ─── Helper: get questions from bank ─────────────────────────────────────────
function getFromBank(subject, chapterKey, category) {
  // chapterKey e.g. "Ch1: Operating System" → extract "1"
  const num = chapterKey.match(/\d+/)?.[0] || "1";
  const subjectKey = subject.toLowerCase().replace(/\s+/g, "");
  const key = `${subjectKey}::${num}::${category}`;
  return questionBank[key] || questionBank[`${subjectKey}::${num}::exercise`] || null;
}

export function generatePaper(config) {
  const { classNo, subject, board, selectionType, selectionMode, chapters, topics,
          category, hasChoice, totalMarks, customCounts } = config;

  const chapterList = syllabus[classNo]?.[subject]?.[board]?.chapters || [];

  let mcqCount, sqCount, lqCount;
  if (selectionType === "custom") {
    mcqCount = customCounts.mcq; sqCount = customCounts.sq; lqCount = customCounts.lq;
  } else {
    const cfg = marksConfig[totalMarks] || marksConfig[25];
    mcqCount = cfg.mcq; sqCount = cfg.sq; lqCount = cfg.lq;
  }

  const srcChapters = selectionMode === "chapterwise" && chapters.length
    ? chapters : chapterList;

  const shuffle = (arr) => [...arr].sort(() => Math.random() - 0.5);
  const pickN   = (arr, n) => shuffle(arr).slice(0, n).concat(
    arr.length < n ? Array.from({ length: n - arr.length }, (_, i) => arr[i % arr.length]) : []
  );

  // Try to pull real questions from the bank for each chapter
  const allMcqs = [], allSqs = [], allLqs = [];
  const usedChapters = srcChapters.length ? srcChapters : chapterList;

  usedChapters.forEach((ch) => {
    const bank = getFromBank(subject, ch, category || "exercise");
    if (bank) {
      bank.mcqs?.forEach((q) => allMcqs.push({ ...q, type: "mcq", chapter: ch }));
      bank.sqs?.forEach((q)  => allSqs.push({ ...q, type: "sq",  chapter: ch }));
      bank.lqs?.forEach((q)  => allLqs.push({ ...q, type: "lq",  chapter: ch }));
    } else {
      // fallback placeholder
      allMcqs.push({ type: "mcq", chapter: ch, q: `Which statement about "${ch}" is correct?`, options: ["Option A", "Option B", "Option C", "Option D"] });
      allSqs.push({ type: "sq", chapter: ch, q: `Define a key concept from "${ch}".` });
      allLqs.push({ type: "lq", chapter: ch, q: `Explain the main principles of "${ch}" with examples.` });
    }
  });

  return {
    mcqs: pickN(allMcqs, mcqCount),
    sqs:  pickN(allSqs,  sqCount),
    lqs:  pickN(allLqs,  lqCount),
    meta: { classNo, subject, board, totalMarks: mcqCount * 1 + sqCount * 3 + lqCount * 5, hasChoice, selectionType },
  };
}
